/** The glyph for a character ('?' for anything outside the set). */
inline const Glyph& glyph (char c)
{
    for (auto& g : kGlyphs)
        if (g.c == c)
            return g;
    for (auto& g : kGlyphs)
        if (g.c == '?')
            return g;
    return kGlyphs[0];
}

inline bool lit (const Glyph& g, int col, int row) { return g.rows[row][col] == '#'; }
